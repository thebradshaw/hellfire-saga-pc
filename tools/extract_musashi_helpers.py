#!/usr/bin/env python3
"""
Extracts the 68000 interpreter's shift/rotate handlers and MUL/DIV cycle
counters from Musashi (third_party/gpgx-wide/core/m68k/m68kops.h) and
rewrites them as helper functions for recompiled code. The result,
src/recomp/rt_helpers.h, is committed; run this again only if the vendored
core changes.

    python3 tools/extract_musashi_helpers.py
"""
import re, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OPS = os.path.join(ROOT, "third_party/gpgx-wide/core/m68k/m68kops.h")
OUT = os.path.join(ROOT, "src/recomp/rt_helpers.h")

src = open(OPS, newline="").read().replace("\r\n", "\n")

def body(name):
    m = re.search(r"^(?:static void m68k_op_|INLINE void )%s\(([^)]*)\)\n\{\n(.*?)\n\}\n" % re.escape(name), src, re.S | re.M)
    if not m:
        sys.exit("not found: " + name)
    return m.group(1), m.group(2)

def keep_32bit_branch(b):
    # M68K_USE_64_BIT is off: keep the #else part
    out, mode = [], None
    for line in b.split("\n"):
        s = line.strip()
        if s.startswith("#if M68K_USE_64_BIT"): mode = "skip"; continue
        if s.startswith("#else") and mode == "skip": mode = "keep"; continue
        if s.startswith("#endif") and mode: mode = None; continue
        if mode == "skip": continue
        out.append(line)
    return "\n".join(out)

def convert(b):
    b = keep_32bit_branch(b)
    b = b.replace("uint* r_dst = &DY;", "u32* r_dst = &DAR[ry];")
    b = b.replace("(((REG_IR >> 9) - 1) & 7) + 1", "cnt")
    b = b.replace("DX & 0x3f", "DAR[rx] & 0x3f")
    b = b.replace("uint ea = EA_AY_AI_16();", "")
    b = b.replace("m68ki_read_16(ea)", "R16(ea)")
    b = b.replace("m68ki_write_16(ea, res)", "W16(ea, res)")
    b = re.sub(r"\buint64\b", "u32", b)
    b = re.sub(r"\buint\b", "u32", b)
    b = re.sub(r"\bsint\b", "s32", b)
    b = re.sub(r"\buint32\b", "u32", b)
    b = re.sub(r"\bsint32\b", "s32", b)
    b = re.sub(r"\buint16\b", "u16", b)
    b = re.sub(r"\bsint16\b", "s16", b)
    b = b.replace("m68ki_cpu.refresh_cycles", "REFRESH")
    for bad in ("REG_IR", "DX", "DY", "OPER_", "EA_"):
        if re.search(r"\b" + bad, b):
            sys.exit("unconverted %s in:\n%s" % (bad, b))
    return b

out = []
out.append("/*\n * rt_helpers.h - generated by tools/extract_musashi_helpers.py from the\n"
           " * Musashi 68000 core in third_party/gpgx-wide (same license). Do not edit.\n"
           " *\n * Shift/rotate handlers and MUL/DIV cycle counters, so recompiled code\n"
           " * matches the interpreter exactly, flags and cycles included.\n */\n")

for fn in ("UseDivuCycles", "UseDivsCycles", "UseMuluCycles", "UseMulsCycles"):
    args, b = body(fn)
    args = convert(args)
    out.append("static void %s(%s)\n{\n%s\n}\n" % (fn, args, convert(b)))

for t in ("asl", "asr", "lsl", "lsr", "rol", "ror", "roxl", "roxr"):
    for sz in ("8", "16", "32"):
        for form in ("s", "r"):
            _, b = body("%s_%s_%s" % (t, sz, form))
            params = "u32 ry, u32 cnt" if form == "s" else "u32 ry, u32 rx"
            out.append("static void sh_%s_%s_%s(%s)\n{\n%s\n}\n" % (t, sz, form, params, convert(b)))
    _, b = body("%s_16_ai" % t)
    out.append("static void shm_%s(u32 ea)\n{\n%s\n}\n" % (t, convert(b)))

open(OUT, "w").write("\n".join(out))
print("wrote", OUT)
